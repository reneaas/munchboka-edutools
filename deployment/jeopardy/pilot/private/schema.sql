CREATE TABLE IF NOT EXISTS jp_users (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(254) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_login (
    email VARCHAR(254) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    challenge CHAR(64) CHARACTER SET ascii NULL,
    code_hash VARCHAR(255) NULL,
    expires_at BIGINT NOT NULL DEFAULT 0,
    attempts INT NOT NULL DEFAULT 0,
    sent_at BIGINT NOT NULL DEFAULT 0,
    window_at BIGINT NOT NULL DEFAULT 0,
    send_count INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_games (
    id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    owner_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(180) NOT NULL,
    content MEDIUMTEXT NOT NULL,
    revision INT UNSIGNED NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jp_game_owner FOREIGN KEY (owner_id) REFERENCES jp_users(id),
    INDEX jp_owner_updated (owner_id, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_revisions (
    game_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision INT UNSIGNED NOT NULL,
    content MEDIUMTEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (game_id, revision),
    CONSTRAINT jp_revision_game FOREIGN KEY (game_id) REFERENCES jp_games(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_media (
    id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    owner_id BIGINT UNSIGNED NOT NULL,
    mime VARCHAR(32) NOT NULL,
    size INT UNSIGNED NOT NULL,
    width INT UNSIGNED NOT NULL,
    height INT UNSIGNED NOT NULL,
    bytes MEDIUMBLOB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jp_media_owner FOREIGN KEY (owner_id) REFERENCES jp_users(id),
    INDEX jp_media_owner_created (owner_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_mail_budget (
    id INT PRIMARY KEY,
    window_at BIGINT NOT NULL DEFAULT 0,
    send_count INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_shares (
    game_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    content MEDIUMTEXT NOT NULL,
    revision INT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jp_share_game FOREIGN KEY (game_id) REFERENCES jp_games(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
