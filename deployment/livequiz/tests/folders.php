require __DIR__.'/core.php';
// Exercise first-run migration on an existing database, then repeated access.
$db->exec('DROP TABLE lq_library');
check(lq_library($db,1)['folders']===[],'existing database auto-migrates');
check(lq_library($db,1)['folders']===[],'migration/read is repeatable');
$root=lq_organize($db,1,['command'=>'create-folder','name'=>'Matematikk'])['id'];
$sub=lq_organize($db,1,['command'=>'create-folder','name'=>'Algebra','parent'=>$root])['id'];
$leaf=lq_organize($db,1,['command'=>'create-folder','name'=>'Likninger','parent'=>$sub])['id'];
$other=lq_organize($db,2,['command'=>'create-folder','name'=>'Private'])['id'];
rejects(fn()=>lq_organize($db,0,['command'=>'create-folder','name'=>'No']),'anonymous cannot organize');
rejects(fn()=>lq_organize($db,1,['command'=>'create-folder','name'=>'No','parent'=>$other]),'cross-owner parent rejected');
rejects(fn()=>lq_organize($db,1,['command'=>'rename-folder','id'=>$other,'name'=>'No']),'cross-owner folder rename rejected');
rejects(fn()=>lq_organize($db,1,['command'=>'delete-folder','id'=>$other]),'cross-owner folder deletion rejected');
rejects(fn()=>lq_organize($db,1,['command'=>'create-folder','name'=>'  ']),'empty folder name rejected');
rejects(fn()=>lq_organize($db,1,['command'=>'move-folder','id'=>$root,'parent'=>$leaf]),'ancestor into descendant rejected');
rejects(fn()=>lq_organize($db,1,['command'=>'move-folder','id'=>$root,'parent'=>$root]),'self-parent rejected');
$savedFolder=lq_save($db,1,['content'=>$quiz,'folder'=>$sub]);$qid=$savedFolder['id'];
check(lq_library_data($db,1)['quiz_folders'][$qid]===$sub,'new quiz saved directly in folder');
$shareKey=lq_share($db,1,$qid,true)['key'];
$before=lq_quiz($db,1,$qid);
lq_organize($db,1,['command'=>'move-quiz','id'=>$qid,'parent'=>$leaf]);
check(lq_quiz($db,1,$qid)===$before,'moving quiz preserves content and revision');
check(lq_shared_quiz($db,$qid,$shareKey)['id']===$qid,'moving preserves share link');
rejects(fn()=>lq_organize($db,2,['command'=>'move-quiz','id'=>$qid,'parent'=>$other]),'other teacher cannot move quiz');
rejects(fn()=>lq_organize($db,1,['command'=>'move-quiz','id'=>$qid,'parent'=>$other]),'quiz cannot move to another teacher folder');
$count=(int)lq_query($db,'SELECT COUNT(*) FROM lq_quizzes')->fetchColumn();
rejects(fn()=>lq_save($db,1,['content'=>$quiz,'folder'=>$other]),'new quiz cannot target another teacher folder');
check((int)lq_query($db,'SELECT COUNT(*) FROM lq_quizzes')->fetchColumn()===$count,'invalid folder save creates no quiz');
lq_organize($db,1,['command'=>'rename-folder','id'=>$leaf,'name'=>'Likninger 1']);
lq_organize($db,1,['command'=>'delete-folder','id'=>$sub]);
check(lq_library_data($db,1)['folders'][$leaf]['parent']===$root,'folder deletion reparents subfolders');
check(lq_library_data($db,1)['quiz_folders'][$qid]===$leaf,'nested quiz preserved');
lq_organize($db,1,['command'=>'delete-folder','id'=>$leaf]);
check(lq_library_data($db,1)['quiz_folders'][$qid]===$root,'folder deletion moves direct quiz up');
lq_organize($db,1,['command'=>'delete-folder','id'=>$root]);
check(!isset(lq_library_data($db,1)['quiz_folders'][$qid]),'root folder deletion unfiles quiz');
check(lq_quiz($db,1,$qid)['id']===$qid,'deleting folders never deletes quiz');
$destination=lq_organize($db,1,['command'=>'create-folder','name'=>'New'])['id'];
lq_organize($db,1,['command'=>'move-quiz','id'=>$qid,'parent'=>$destination]);
lq_save($db,1,['id'=>$qid,'revision'=>1,'content'=>$quiz]);
check(lq_library_data($db,1)['quiz_folders'][$qid]===$destination,'editing quiz preserves folder');
lq_delete($db,1,['id'=>$qid]);
check(!isset(lq_library_data($db,1)['quiz_folders'][$qid]),'quiz deletion cleans folder metadata');
check(count(lq_library($db,2)['folders'])===1,'libraries isolated');
